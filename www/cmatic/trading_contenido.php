			3. Resistencia a la censura: Tanto el oro como el bitcoin tienen la característica de ser resistentes a la censura. Esto significa que no están controlados por ningún gobierno o entidad centralizada, lo que les da a sus poseedores una mayor autonomía y control sobre su riqueza.<br><br>
			4. Portabilidad: Tanto el oro como el bitcoin son fácilmente transferibles y pueden ser enviados de una parte a otra de forma rápida y segura. En el caso del bitcoin, su naturaleza digital permite que las transacciones se realicen de manera instantánea a través de la red blockchain.<br><br>
