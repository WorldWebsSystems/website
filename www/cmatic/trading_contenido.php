			3. Litecoin (LTC): Considerada la "plata" del Bitcoin, tiene tiempos de bloque más rápidos y utiliza un algoritmo de minería diferente.<br><br>
			4. Bitcoin Cash (BCH): Nació como una bifurcación (fork) del Bitcoin original para aumentar el tamaño del bloque y permitir transacciones más rápidas y con menores comisiones.<br><br><br>
